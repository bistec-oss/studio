import { describe, it, expect } from 'vitest'
import { readdirSync, readFileSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'

// AC-09 (012 FR-20): where the UI means the post caption it says "caption",
// not "copy". Every .ts/.tsx file under src/app and src/components is scanned
// for the old strings. Whitespace is collapsed and `&amp;` is read as `&`, so
// a string a JSX line break splits, or an escaped ampersand, is still caught.
//
// The first five are AC-09's list; the rest are FR-20's remaining table rows.
// FR-20's "deliberately unchanged" strings (the COPY provider slot and the
// clipboard sense) must pass, which the second self-test pins.

const ROOTS = ['src/app', 'src/components'].map((d) => resolve(process.cwd(), d))

const OLD_WORDING = [
  'Brief & Copy Direction',
  'Writing the copy',
  'Post copy',
  'Generating copy',
  'title="Copy"',
  'injected into copy and design',
  'Copy is generated by Claude',
  'so copy is generated on the Claude OAuth chain',
  'not ready for copy regeneration',
  'its copy can no longer be edited',
  'Failed to regenerate copy',
]

function oldWording(source: string): string[] {
  const text = source.replace(/&amp;/g, '&').replace(/\s+/g, ' ')
  return OLD_WORDING.filter((s) => text.includes(s))
}

function sourceFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = join(dir, e.name)
    if (e.isDirectory()) return sourceFiles(p)
    return /\.tsx?$/.test(e.name) ? [p] : []
  })
}

describe('caption wording under src/app and src/components (AC-09)', () => {
  it('no source file uses the old "copy" wording', () => {
    const offenders = ROOTS.flatMap(sourceFiles).flatMap((f) =>
      oldWording(readFileSync(f, 'utf8')).map((s) => `${relative(process.cwd(), f)}: ${s}`),
    )
    expect(offenders).toEqual([])
  })

  it('self-test: flags each old string, including split and escaped forms', () => {
    for (const sample of [
      `<StepHead index={2} title={<>Brief &amp; Copy Direction</>}>`,
      `<Loader2 /> Writing the copy…`,
      `placeholder="Post copy…"`,
      `aria-label="Generating copy"`,
      `<SectionHead title="Copy">`,
      `— injected into copy and\n        design prompts alongside the brand voice.`,
      `key) — the only key this team needs. Copy is generated by Claude on the OAuth chain.`,
      `CLI mode, so copy is generated on the Claude OAuth chain — a`,
      `{ error: 'Draft is not ready for copy regeneration' }`,
      `'This draft has been published — its copy can no longer be edited'`,
      `toast.error('Failed to regenerate copy')`,
    ]) {
      expect(oldWording(sample), sample).toHaveLength(1)
    }
  })

  it('self-test: passes the new wording and the deliberately unchanged strings', () => {
    for (const sample of [
      `<StepHead index={2} title={<>Brief &amp; Caption Direction</>}>`,
      `<Loader2 /> Writing the captions…`,
      `placeholder={\`Write the \${spec.label} caption…\`}`,
      `{ value: 'COPY', label: 'COPY' },`,
      `{slot === 'COPY' ? 'Copy (text generation)' : 'Image generation'}`,
      `text: \`\${p.slot === 'COPY' ? 'Copy' : 'Image'} provider added — \${p.label}\`,`,
      `'No copy provider is configured, and the server is not in CLI mode. Ask an admin to add a COPY provider in AI Providers.'`,
      `member&apos;s personal token, falling back to the team token. No copy provider is needed;`,
      `aria-label={\`Copy \${spec.label} caption\`}`,
      `aria-label="Copy command"`,
      `<Copy {...ICON} /> Copy key`,
      `toast.success('Caption copied')`,
    ]) {
      expect(oldWording(sample), sample).toEqual([])
    }
  })
})
